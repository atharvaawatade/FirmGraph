"""[8] EXPORT: machine-readable artifacts + the evidence-pack scaffold.

The evidence pack is the seed of the product thesis: everything the scan
knows, organised the way an audit conversation needs it — plus an honest
README saying exactly what the manufacturer still owns. We draft; they sign.
"""

from __future__ import annotations

import json
import shutil

from firmgraph.cra.mapping import MAPPING_DISCLAIMER, aggregate_mapping
from firmgraph.graph.repository import GraphRepository
from firmgraph.pipeline.context import ScanContext
from firmgraph.pipeline.manifest import build_manifest
from firmgraph.report.renderer import LIABILITY_LINE
from firmgraph.stages.base import Stage
from firmgraph.vex import build_cyclonedx_vex, build_openvex

_EVIDENCE_README = """\
# FirmGraph Evidence Pack — `{scan_id}`

Generated by FirmGraph {version}. Fully local; nothing left this machine.

## What is in this pack

| File | Contents |
|---|---|
| `manifest.json` | Reproducibility receipt: image hash, tool versions, DB snapshot dates, stage provenance |
| `findings.json` | Every finding with priority, reason, reachability, fix status — including suppressed ones (marked, never deleted) |
| `cra-mapping.json` | Best-effort mapping of findings to CRA (EU 2024/2847) Annex I essential requirements |
| `vex.openvex.json`, `vex.cdx.json` | **VEX** (OpenVEX + CycloneDX): drafted exploitability statements — which CVEs matter, which are assessed not_affected and why |
| `../sbom.cdx.json`, `../sbom.spdx.json` | SBOM exports (CycloneDX / SPDX) — supports Annex I Part II(1) documentation |

## What this pack is NOT

{liability}

{disclaimer}

## What the manufacturer still owns (this pack does not replace it)

- [ ] Risk assessment for the product (Annex I Part I(1))
- [ ] EU Declaration of Conformity — drafted, reviewed, and **signed by you**
- [ ] Support-period and security-update policy
- [ ] Coordinated vulnerability disclosure policy (Annex I Part II(5))
- [ ] ENISA reporting readiness (24h/72h/14d obligations, from 11 Sep 2026)
"""


class ExportStage(Stage):
    name = "export"

    def execute(self, ctx: ScanContext) -> list[str] | None:
        ctx.out_dir.mkdir(parents=True, exist_ok=True)
        exported: list[str] = []

        sbom_dir = ctx.work_dir / "sbom"
        if sbom_dir.is_dir():  # CycloneDX + SPDX + syft-json written by the SBOM engine
            for doc in sorted(sbom_dir.glob("sbom.*.json")):
                shutil.copy2(doc, ctx.out_dir / doc.name)
                exported.append(doc.name)

        repo = GraphRepository(ctx.db_path)
        try:
            node_ids = sorted(repo.node_ids(ctx.scan_id))
        finally:
            repo.close()
        graph_payload = {
            "scan_id": ctx.scan_id,
            "image_sha256": ctx.image_sha256,
            "node_ids": node_ids,
            "format": "firmgraph-graph-v1",
        }
        graph_path = ctx.out_dir / "graph.json"
        graph_path.write_text(
            json.dumps(graph_payload, indent=2, sort_keys=True), encoding="utf-8"
        )
        exported.append(f"{graph_path.name} ({len(node_ids)} nodes)")

        exported.append(self._write_evidence_pack(ctx))
        return ["wrote " + ", ".join(exported)]

    def _write_evidence_pack(self, ctx: ScanContext) -> str:
        pack = ctx.out_dir / "evidence-pack"
        pack.mkdir(parents=True, exist_ok=True)
        manifest = build_manifest(ctx)

        (pack / "manifest.json").write_text(
            manifest.model_dump_json(indent=2), encoding="utf-8"
        )
        (pack / "findings.json").write_text(
            json.dumps(
                [f.model_dump() for f in ctx.findings], indent=2, sort_keys=True
            ),
            encoding="utf-8",
        )
        cra_payload = [
            {
                "requirement": row.ref.req_id,
                "title": row.ref.title,
                "finding_ids": list(row.finding_ids),
            }
            for row in aggregate_mapping(ctx.findings)
        ]
        (pack / "cra-mapping.json").write_text(
            json.dumps(
                {"disclaimer": MAPPING_DISCLAIMER, "mapping": cra_payload},
                indent=2,
                sort_keys=True,
            ),
            encoding="utf-8",
        )
        (pack / "vex.openvex.json").write_text(
            json.dumps(build_openvex(manifest, ctx.findings), indent=2, sort_keys=True),
            encoding="utf-8",
        )
        (pack / "vex.cdx.json").write_text(
            json.dumps(build_cyclonedx_vex(manifest, ctx.findings), indent=2, sort_keys=True),
            encoding="utf-8",
        )
        (pack / "README.md").write_text(
            _EVIDENCE_README.format(
                scan_id=ctx.scan_id,
                version=ctx.firmgraph_version,
                liability=LIABILITY_LINE,
                disclaimer=MAPPING_DISCLAIMER,
            ),
            encoding="utf-8",
        )
        return "evidence-pack/ (manifest, findings, cra-mapping, VEX ×2, README)"
